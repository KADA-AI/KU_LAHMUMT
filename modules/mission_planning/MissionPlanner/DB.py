FOV_SELECTION_PREFERENCE = 0.65

try:
    from .runtime_settings import load_fov_db_rows as _load_runtime_fov_db_rows
except Exception:
    try:
        from runtime_settings import load_fov_db_rows as _load_runtime_fov_db_rows  # type: ignore
    except Exception:
        _load_runtime_fov_db_rows = None


def _flatten_entries():
    """FOV_DB를 평탄화해서 리스트로 반환."""
    if _load_runtime_fov_db_rows is not None:
        try:
            rows = _load_runtime_fov_db_rows()
        except Exception:
            rows = []
        if rows:
            return [dict(row) for row in rows]

    rows = []
    for fov, sep_map in FOV_DB.items():
        for _sep, data in sep_map.items():
            row = dict(data)
            row["fov"] = float(fov)
            rows.append(row)
    return rows


def select_best_config(span):
    """
    span 이상인 width 중 vel 최대(동률이면 fov 최대)를 선택.
    span보다 큰 width가 없으면 가장 큰 width를 선택.
    """
    entries = _flatten_entries()
    if not entries:
        raise ValueError("FOV_DB 가 비어 있습니다.")

    candidates = [e for e in entries if e["width"] >= span]
    if not candidates:
        max_width = max(entries, key=lambda e: e["width"])["width"]
        candidates = [e for e in entries if e["width"] == max_width]

    if len(candidates) == 1:
        return candidates[0]

    span_f = float(span)
    fov_values = [float(e.get("fov", 0.0) or 0.0) for e in candidates]
    vel_values = [float(e.get("vel", 0.0) or 0.0) for e in candidates]
    fov_scale = max(max(fov_values) - min(fov_values), 1e-9)
    vel_scale = max(max(vel_values) - min(vel_values), 1e-9)

    max_fov_row = max(
        candidates,
        key=lambda e: (
            float(e.get("fov", 0.0) or 0.0),
            float(e.get("vel", 0.0) or 0.0),
            -max(float(e.get("width", 0.0) or 0.0) - span_f, 0.0),
            float(e.get("sep", 0.0) or 0.0),
        ),
    )
    max_vel_row = max(
        candidates,
        key=lambda e: (
            float(e.get("vel", 0.0) or 0.0),
            float(e.get("fov", 0.0) or 0.0),
            -max(float(e.get("width", 0.0) or 0.0) - span_f, 0.0),
            float(e.get("sep", 0.0) or 0.0),
        ),
    )
    target_fov = (
        (float(max_fov_row.get("fov", 0.0) or 0.0) * FOV_SELECTION_PREFERENCE)
        + (float(max_vel_row.get("fov", 0.0) or 0.0) * (1.0 - FOV_SELECTION_PREFERENCE))
    )
    target_vel = (
        float(max_fov_row.get("vel", 0.0) or 0.0)
        + float(max_vel_row.get("vel", 0.0) or 0.0)
    ) / 2.0

    best = min(
        candidates,
        key=lambda e: (
            (
                ((float(e.get("fov", 0.0) or 0.0) - target_fov) / fov_scale) ** 2
                + ((float(e.get("vel", 0.0) or 0.0) - target_vel) / vel_scale) ** 2
            ),
            max(float(e.get("width", 0.0) or 0.0) - span_f, 0.0),
            -float(e.get("sep", 0.0) or 0.0),
            -float(e.get("fov", 0.0) or 0.0),
            -float(e.get("vel", 0.0) or 0.0),
        ),
    )
    return best
